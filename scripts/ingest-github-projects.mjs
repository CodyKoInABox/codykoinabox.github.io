/**
 * Seeds lib/projects/catalog/github.ts from GitHub star lists + public repos.
 * Does not run at build time. Re-run when lists change:
 *   node scripts/ingest-github-projects.mjs
 */
import { writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const USER = "CodyKoInABox"
const UA = "codykoinabox-portfolio-ingest"
const EXCLUDE = new Set([
  `${USER}/codykoinabox.github.io`.toLowerCase(),
  `${USER}/CodyKoInABox`.toLowerCase(),
])
const LISTS = [
  { slug: "personal-projects", kind: "personal" },
  { slug: "college", kind: "college" },
]

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const outFile = path.join(root, "lib/projects/catalog/github.ts")

function decode(html) {
  return html
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/\s+/g, " ")
    .trim()
}

function githubSlug(owner, repo) {
  return `${owner}-${repo}`.toLowerCase()
}

function keyOf(owner, repo) {
  return `${owner}/${repo}`.toLowerCase()
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      "User-Agent": UA,
      Accept: url.includes("api.github.com")
        ? "application/vnd.github+json"
        : "text/html",
    },
  })
  if (!response.ok) {
    throw new Error(`${response.status} ${url}`)
  }
  return response.text()
}

function parseListPage(html) {
  const section = html.split('id="user-list-repositories"')[1]
  if (!section) return []

  const cards = section.split('class="col-12 d-block width-full')
  const items = []

  for (const card of cards) {
    const href = card.match(/<h2 class="h3">\s*<a href="\/([^/]+)\/([^"]+)">/)
    if (!href) continue

    const owner = href[1]
    const repo = href[2]
    const descriptionMatch = card.match(
      /itemprop="description">\s*([^<]*)\s*<\/p>/
    )
    const languageMatch = card.match(
      /itemprop="programmingLanguage">([^<]+)<\/span>/
    )
    const updatedMatch = card.match(/<relative-time datetime="([^"]+)"/)

    items.push({
      owner,
      repo,
      description: decode(descriptionMatch?.[1] ?? ""),
      language: decode(languageMatch?.[1] ?? ""),
      updatedAt: updatedMatch?.[1] ?? "1970-01-01T00:00:00Z",
      url: `https://github.com/${owner}/${repo}`,
    })
  }

  return items
}

async function fetchList(listSlug) {
  const items = []
  for (let page = 1; page <= 20; page += 1) {
    const url = `https://github.com/stars/${USER}/lists/${listSlug}?page=${page}`
    const html = await fetchText(url)
    const pageItems = parseListPage(html)
    if (pageItems.length === 0) break
    items.push(...pageItems)
    if (pageItems.length < 30) break
  }
  return items
}

async function fetchOwnedRepos() {
  const repos = []
  for (let page = 1; page <= 10; page += 1) {
    const url = `https://api.github.com/users/${USER}/repos?per_page=100&page=${page}&type=owner&sort=updated`
    const json = JSON.parse(await fetchText(url))
    if (!Array.isArray(json) || json.length === 0) break
    for (const repo of json) {
      repos.push({
        owner: repo.owner.login,
        repo: repo.name,
        description: repo.description ?? "",
        language: repo.language ?? "",
        updatedAt: repo.updated_at,
        url: repo.html_url,
      })
    }
    if (json.length < 100) break
  }
  return repos
}

function toProject(kind, item) {
  const summary = item.description
  return {
    slug: githubSlug(item.owner, item.repo),
    kind,
    title: { en: item.repo, pt: item.repo },
    summary: { en: summary, pt: summary },
    languages: item.language ? [item.language] : [],
    source: {
      type: "github",
      owner: item.owner,
      repo: item.repo,
      url: item.url,
    },
    updatedAt: item.updatedAt,
  }
}

function serialize(projects) {
  return `import type { Project } from "@/lib/projects/types"

/** Generated by scripts/ingest-github-projects.mjs. Edit via catalog/manual.ts. */
export const githubProjects = ${JSON.stringify(projects, null, 2)} as const satisfies readonly Project[]
`
}

const owned = await fetchOwnedRepos()
const ownedByKey = new Map(owned.map((item) => [keyOf(item.owner, item.repo), item]))

const listedKind = new Map()
const listedItem = new Map()

for (const list of LISTS) {
  const items = await fetchList(list.slug)
  for (const item of items) {
    const key = keyOf(item.owner, item.repo)
    if (listedKind.has(key)) continue
    listedKind.set(key, list.kind)
    listedItem.set(key, ownedByKey.get(key) ?? item)
  }
}

const projects = []
const seenSlug = new Set()

for (const [key, kind] of listedKind) {
  const item = listedItem.get(key)
  const project = toProject(kind, item)
  if (seenSlug.has(project.slug)) {
    throw new Error(`duplicate slug ${project.slug}`)
  }
  seenSlug.add(project.slug)
  projects.push(project)
}

for (const item of owned) {
  const key = keyOf(item.owner, item.repo)
  if (listedKind.has(key)) continue
  if (EXCLUDE.has(key)) continue
  const project = toProject("other", item)
  if (seenSlug.has(project.slug)) {
    throw new Error(`duplicate slug ${project.slug}`)
  }
  seenSlug.add(project.slug)
  projects.push(project)
}

projects.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))

await writeFile(outFile, serialize(projects), "utf8")

const counts = { personal: 0, college: 0, professional: 0, other: 0 }
for (const project of projects) counts[project.kind] += 1
console.log(
  `wrote ${projects.length} projects → ${path.relative(root, outFile)}`,
  counts
)
